export type TransportMode = 'PACK30' | 'MESSAGERIE_PLUS' | 'AFFRETEMENT'

export interface TransportCalculation {
  basePrice: number
  fuelSurcharge: number
  subtotal: number
  options: number
  total: number
  zone?: string
}

export function calculateTransport(
  mode: TransportMode,
  department: string,
  weightKg: number,
  units: number,
  fuelSurchargePercent: number,
  options: number = 0
): TransportCalculation | null {
  let basePrice: number | null = null
  let zone: string | undefined

  if (mode === 'PACK30') {
    basePrice = getPack30Rate(department, weightKg)
    zone = PACK30_ZONES[department] ?? 'Z02'
  } else if (mode === 'MESSAGERIE_PLUS') {
    basePrice = getMessagerieRate(department, weightKg)
    zone = MESSAGERIE_ZONES[department] ?? 'Z06'
  } else if (mode === 'AFFRETEMENT') {
    basePrice = getAffretementRate(department, units)
    zone = `${units} palettes`
  }

  if (basePrice === null) return null

  const fuelSurcharge = Math.round(basePrice * (fuelSurchargePercent / 100) * 100) / 100
  const subtotal = Math.round((basePrice + fuelSurcharge) * 100) / 100
  const total = Math.round((subtotal + options) * 100) / 100

  return { basePrice, fuelSurcharge, subtotal, options, total, zone }
}

// Suggestion de mode selon poids et unités
export function suggestTransportMode(weightKg: number, palettes: number): TransportMode {
  if (weightKg <= 30 && palettes <= 1) return 'PACK30'
  if (palettes >= 2 && weightKg >= 500) return 'AFFRETEMENT'
  return 'MESSAGERIE_PLUS'
}